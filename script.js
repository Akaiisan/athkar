document.addEventListener('DOMContentLoaded', () => {
    // --- State Management ---
    let currentCategoryIndex = parseInt(sessionStorage.getItem('dhikr-current-category') || '0');
    if (isNaN(currentCategoryIndex) || currentCategoryIndex >= dhikrCategories.length) {
        currentCategoryIndex = 0;
    }

    let adhkarCounts = [];

    // --- DOM Elements ---
    const categoryList = document.getElementById('categoryList');
    const currentCategoryTitle = document.getElementById('currentCategoryTitle');
    const completedCountDisplay = document.getElementById('completedCount');
    const dhikrTotalDisplay = document.getElementById('dhikrTotal');
    const categoryProgressFill = document.getElementById('categoryProgressFill');
    const adhkarContainer = document.getElementById('adhkarContainer');
    const themeToggle = document.getElementById('themeToggle');
    const mobileMenuBtn = document.getElementById('mobileMenuBtn');
    const mobileMenu = document.getElementById('mobileMenu');

    // --- LocalStorage Helpers ---
    function getSaveKey(index = currentCategoryIndex) {
        return 'dhikr-progress-' + dhikrCategories[index].id;
    }

    function saveProgress() {
        sessionStorage.setItem(getSaveKey(), JSON.stringify(adhkarCounts));
        sessionStorage.setItem('dhikr-current-category', currentCategoryIndex);
    }

    function loadProgress() {
        const category = dhikrCategories[currentCategoryIndex];
        const saved = sessionStorage.getItem(getSaveKey());
        
        // Initialize with zeros by default
        adhkarCounts = new Array(category.adhkar.length).fill(0);

        if (saved) {
            try {
                const parsed = JSON.parse(saved);
                // Ensure length matches to avoid index out of bounds if data changed
                if (Array.isArray(parsed) && parsed.length === category.adhkar.length) {
                    adhkarCounts = parsed;
                    return true;
                }
            } catch (e) {
                console.error("Error loading progress:", e);
            }
        }
        return false;
    }

    // --- UI Helpers ---
    function setRingProgress(ringElement, percent) {
        if (!ringElement) return;
        const radius = ringElement.r.baseVal.value;
        const circumference = radius * 2 * Math.PI;

        if (!ringElement.style.strokeDasharray) {
            ringElement.style.strokeDasharray = `${circumference} ${circumference}`;
        }

        const offset = circumference - (Math.min(percent, 100) / 100) * circumference;
        ringElement.style.strokeDashoffset = offset;
    }

    function updateCategoryProgress() {
        const category = dhikrCategories[currentCategoryIndex];
        const total = category.adhkar.length;

        let completed = 0;
        category.adhkar.forEach((dhikr, idx) => {
            if (adhkarCounts[idx] >= dhikr.target) {
                completed++;
            }
        });

        completedCountDisplay.textContent = completed;
        dhikrTotalDisplay.textContent = total;

        const progressPercent = (completed / total) * 100;
        if (categoryProgressFill) {
            categoryProgressFill.style.width = `${progressPercent}%`;
        }
    }

    function showToast(message) {
        const toastContainer = document.getElementById('toastContainer');
        if (!toastContainer) return;

        const toast = document.createElement('div');
        toast.className = 'toast';
        toast.textContent = message;

        toastContainer.appendChild(toast);

        setTimeout(() => toast.classList.add('show'), 10);

        setTimeout(() => {
            toast.classList.remove('show');
            setTimeout(() => toast.remove(), 300);
        }, 3000);
    }

    // --- Main Rendering Logic ---
    function initCategories() {
        categoryList.innerHTML = '';
        dhikrCategories.forEach((cat, index) => {
            const li = document.createElement('li');
            li.className = `category-item ${index === currentCategoryIndex ? 'active' : ''}`;
            li.innerHTML = `<i class="ph ${cat.icon}"></i> ${cat.name}`;
            li.addEventListener('click', () => {
                currentCategoryIndex = index;
                updateCategoryUI();
                renderAdhkarList();
                saveProgress(); // Save the new category index
                
                // Close mobile menu if open
                if (mobileMenu.classList.contains('open')) {
                    mobileMenu.classList.remove('open');
                    mobileMenuBtn.innerHTML = '<i class="ph ph-list"></i>';
                }
            });
            categoryList.appendChild(li);
        });
    }

    function updateCategoryUI() {
        document.querySelectorAll('.category-item').forEach((el, index) => {
            el.className = `category-item ${index === currentCategoryIndex ? 'active' : ''}`;
        });
    }

    function renderAdhkarList() {
        const category = dhikrCategories[currentCategoryIndex];
        currentCategoryTitle.textContent = category.name;
        adhkarContainer.innerHTML = '';

        // Load saved state for this category
        loadProgress();
        updateCategoryProgress();

        category.adhkar.forEach((dhikr, index) => {
            const card = document.createElement('div');
            card.className = 'glass-card dhikr-card';
            
            const isCompleted = adhkarCounts[index] >= dhikr.target;
            if (isCompleted) card.classList.add('completed');

            card.innerHTML = `
                <div class="completion-badge">
                    <i class="ph ph-check-circle"></i>
                </div>
                <div class="dhikr-text-container">
                    <p class="arabic-text">${dhikr.text}</p>
                    <div class="fadl-box">
                        <p class="translation-text" dir="auto">${dhikr.translation}</p>
                    </div>
                </div>
                <div class="counter-container">
                    <button class="counter-btn" aria-label="Increment Counter">
                        <svg class="progress-ring" width="140" height="140" viewBox="0 0 140 140">
                            <circle class="progress-ring-bg" stroke="rgba(0,0,0,0.05)" stroke-width="6" fill="rgba(255,255,255,0.6)" r="66" cx="70" cy="70"/>
                            <circle class="progress-ring-circle" stroke="var(--accent-sage)" stroke-width="6" fill="transparent" r="66" cx="70" cy="70" stroke-linecap="round"/>
                        </svg>
                        <span class="count-display">${adhkarCounts[index]}</span>
                    </button>
                    <div class="target-text">الهدف: <span>${dhikr.target}</span></div>
                    
                    <div class="action-buttons">
                        <button class="reset-btn" aria-label="Reset Counter" title="إعادة تعيين">
                            <i class="ph ph-arrow-counter-clockwise"></i> إعادة
                        </button>
                    </div>
                </div>
            `;

            const countDisplay = card.querySelector('.count-display');
            const progressRing = card.querySelector('.progress-ring-circle');
            const resetBtn = card.querySelector('.reset-btn');

            // Set initial ring state
            const initialPercent = (adhkarCounts[index] / dhikr.target) * 100;
            setRingProgress(progressRing, initialPercent);

            // Increment Logic
            card.addEventListener('click', (e) => {
                if (e.target.closest('.reset-btn')) return;

                if (adhkarCounts[index] < dhikr.target) {
                    adhkarCounts[index]++;
                    countDisplay.textContent = adhkarCounts[index];

                    const percent = (adhkarCounts[index] / dhikr.target) * 100;
                    setRingProgress(progressRing, percent);

                    if (navigator.vibrate) navigator.vibrate(15);

                    if (adhkarCounts[index] === dhikr.target) {
                        card.classList.add('completed');
                        showToast('تم إكمال الذكر بنجاح ✨');
                        if (navigator.vibrate) navigator.vibrate([30, 50, 30]);
                    }

                    updateCategoryProgress();
                    saveProgress();
                }
            });

            // Reset Logic
            resetBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                adhkarCounts[index] = 0;
                countDisplay.textContent = 0;
                setRingProgress(progressRing, 0);
                card.classList.remove('completed');
                updateCategoryProgress();
                saveProgress();

                if (navigator.vibrate) navigator.vibrate([20, 50, 20]);
            });

            // Prevent mobile zoom on double tap
            let lastTap = 0;
            card.addEventListener('touchstart', (e) => {
                if (e.target.closest('.reset-btn')) return;
                const currentTime = new Date().getTime();
                const tapLength = currentTime - lastTap;
                if (tapLength < 500 && tapLength > 0) e.preventDefault();
                lastTap = currentTime;
            }, { passive: false });

            adhkarContainer.appendChild(card);
        });
    }

    // --- Theme & Mobile Menu ---
    function applyTheme(dark) {
        if (dark) {
            document.documentElement.setAttribute('data-theme', 'dark');
            themeToggle.innerHTML = '<i class="ph ph-sun"></i>';
        } else {
            document.documentElement.removeAttribute('data-theme');
            themeToggle.innerHTML = '<i class="ph ph-moon"></i>';
        }
    }

    const savedTheme = localStorage.getItem('dhikr-theme');
    if (savedTheme === 'dark') applyTheme(true);

    themeToggle.addEventListener('click', () => {
        const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
        applyTheme(!isDark);
        localStorage.setItem('dhikr-theme', isDark ? 'light' : 'dark');
    });

    mobileMenuBtn.addEventListener('click', () => {
        mobileMenu.classList.toggle('open');
        const isOpen = mobileMenu.classList.contains('open');
        mobileMenuBtn.innerHTML = isOpen ? '<i class="ph ph-x"></i>' : '<i class="ph ph-list"></i>';
    });

    // --- Back to Top Logic ---
    const backToTopBtn = document.getElementById('backToTop');
    
    window.addEventListener('scroll', () => {
        if (window.scrollY > 300) {
            backToTopBtn.classList.add('show');
        } else {
            backToTopBtn.classList.remove('show');
        }
    });

    backToTopBtn.addEventListener('click', () => {
        window.scrollTo({
            top: 0,
            behavior: 'smooth'
        });
    });

    // --- Initialization ---
    initCategories();
    renderAdhkarList();
});

